filepath = 'D:/长江大学计算机实验室/计算机实验室文件/java/LanguageStudySystem/JavaJapStuSystem/JLPT/JLPTGenerator.java'

with open(filepath, 'rb') as f:
    raw = f.read()

# Detect line ending
if b'\r\n' in raw:
    nl = b'\r\n'
    nl_str = '\r\n'
else:
    nl = b'\n'
    nl_str = '\n'

# Find header and footer
header_bytes = b'    static final List<Word> N3_WORDS = Arrays.asList(' + nl
header_idx = raw.find(header_bytes)

body_start = header_idx + len(header_bytes)
footer_bytes = nl + b'    );'
footer_idx = raw.find(footer_bytes, body_start)

print(f'Header at byte {header_idx}, Footer at byte {footer_idx}')

# Extract body
body_raw = raw[body_start:footer_idx]
lines = body_raw.split(nl)

processed_lines = []
modified = 0
errors = 0

for i, line in enumerate(lines):
    if not line.strip():
        # Skip empty trailing line from split
        if i == len(lines) - 1:
            continue
        processed_lines.append(line)
        continue
    
    line_str = line.decode('utf-8')
    m = re.match(r'^(\s*new Word\()"([^"]+)",\s*"([^"]+)"\)(\s*[,;]?\s*)$', line_str)
    if m:
        indent = m.group(1)
        word = m.group(2)
        meaning = m.group(3)
        ending = m.group(4).rstrip()
        
        if word in readings:
            reading = readings[word]
            new_line_str = f'{indent}"{word}","{reading}","{meaning}"){ending}'
            processed_lines.append(new_line_str.encode('utf-8'))
            modified += 1
        else:
            print(f'WARNING: No reading for [{word}]')
            processed_lines.append(line)
            errors += 1
    else:
        print(f'WARNING: Cannot parse: {line_str[:80]}')
        processed_lines.append(line)
        errors += 1

# Reconstruct - join with nl, then add footer (which starts with nl)
new_body = nl.join(processed_lines)
# footer_bytes already includes leading nl, so new_body should NOT end with nl
new_content = raw[:header_idx] + header_bytes + new_body + footer_bytes + raw[footer_idx + len(footer_bytes):]

with open(filepath, 'wb') as f:
    f.write(new_content)

print(f'\nDone! Modified {modified} entries, {errors} errors')
print(f'Total lines: {len(lines)}')

# Verify
print('\n=== Verification (first 3) ===')
for line in new_body.split(nl)[:3]:
    if line.strip():
        print(' ', line.decode('utf-8'))

print('\n=== Verification (last 3) ===')
for line in new_body.split(nl)[-3:]:
    if line.strip():
        print(' ', line.decode('utf-8'))
